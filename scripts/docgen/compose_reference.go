// composeRequiredPlaceholders gives an obvious placeholder value for every
// kingpin-Required flag, so the reference compose file's environment: mapping
// has real strings sitting where OPNsense connection details go rather than
// an empty quote. A Required flag with no entry here fails the build (see
// generateComposeReference) instead of rendering an empty placeholder: silently
// missing one is exactly the coverage gap this page exists to close.
var composeRequiredPlaceholders = map[string]string{
	"opnsense.protocol": "https",
	"opnsense.address":  "opnsense.example.com",
}

// composeReceiverPorts documents the three push receivers' listen ports in the
// generated ports: block. Each entry names the flag that turns the receiver on,
// since an operator scanning ports: has no other way to connect "why is this
// commented out" to "what enables it".
type composePort struct {
	published, containerPort, proto string
	enabledBy                       string
	note                            string
}

